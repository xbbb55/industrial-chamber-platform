@app.get("/api/memory/debug")
async def memory_debug() -> dict[str, Any]:
    try:
        shm = attach_existing()
        try:
            info = inspect_memory(shm)
            snapshot = normalize_snapshot(read_snapshot(shm))
        finally:
            shm.close()
    except SharedMemoryNotReady as exc:
        raise HTTPException(status_code=503, detail=str(exc)) from exc

    devices = snapshot.get("devices", [])
    return {
        "memory": info,
        "snapshot_summary": {
            "source": snapshot.get("source"),
            "sequence": snapshot.get("sequence"),
            "written_at": snapshot.get("written_at"),
            "device_count": len(devices),
            "device_ids": [device.get("device_id") for device in devices],
            "fields_per_device": sorted(devices[0].keys()) if devices else [],
        },
        "snapshot": snapshot,
    }


@app.websocket("/ws/memory")
async def memory_websocket(websocket: WebSocket) -> None:
    await websocket.accept()
    command_status_websockets.add(websocket)
    try:
        while True:
            try:
                snapshot = get_realtime_snapshot()
                await websocket.send_json({
                    "type": "memory_snapshot",
                    "router_read_at": time.time(),
                    "snapshot": snapshot,
                })
            except SharedMemoryNotReady as exc:
                await websocket.send_json({
                    "type": "memory_not_ready",
                    "message": str(exc),
                    "router_read_at": time.time(),
                })
            await asyncio.sleep(0.25)
    except WebSocketDisconnect:
        pass
    finally:
        command_status_websockets.discard(websocket)
