@app.post("/api/device-ingest/snapshots")
async def upload_edge_snapshot(upload: EdgeSnapshotUpload, request: Request) -> dict[str, Any]:
    source_ip = request.client.host if request.client else None
    device_ip = upload.device_ip.strip() or source_ip
    normalized_snapshot = normalize_snapshot(upload.snapshot)
    uploaded_edge_snapshots[upload.edge_id] = {
        "edge_id": upload.edge_id,
        "edge_ip": device_ip,
        "device_ip": device_ip,
        "source_ip": source_ip,
        "agent_version": upload.agent_version,
        "uploaded_at": upload.uploaded_at,
        "received_at": time.time(),
        "snapshot": normalized_snapshot,
        "raw_snapshot": upload.snapshot,
    }
    return {
        "status": "accepted",
        "edge_id": upload.edge_id,
        "edge_ip": device_ip,
        "device_ip": device_ip,
        "source_ip": source_ip,
        "received_at": uploaded_edge_snapshots[upload.edge_id]["received_at"],
        "device_count": len(normalized_snapshot.get("devices", [])),
        "sequence": normalized_snapshot.get("sequence"),
    }


